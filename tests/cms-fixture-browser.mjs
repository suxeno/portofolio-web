// Run only against the separate synthetic build, never the production dist.
import {chromium} from 'playwright-core';
import {spawn} from 'node:child_process';
import assert from 'node:assert/strict';
const root = process.argv[2];
if (!root?.includes('cms-test-build')) throw new Error('Expected isolated fixture build directory');
const server = spawn('python3',['-m','http.server','18766','--bind','127.0.0.1','--directory',root],{stdio:'ignore'});
let browser;
try {
  for (let i=0;i<100;i++) { try { if ((await fetch('http://127.0.0.1:18766/')).ok) break; } catch {} await new Promise(r=>setTimeout(r,100)); }
  browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH || '/usr/bin/chromium',args:['--no-sandbox','--disable-gpu']});
  const page=await browser.newPage({viewport:{width:320,height:900}});
  await page.goto('http://127.0.0.1:18766/writing/test-only-article/');
  assert.equal(await page.title(),'TEST article SEO');
  assert.equal(await page.locator('meta[name="description"]').getAttribute('content'),'TEST article description');
  assert.match(await page.locator('meta[property="og:image"]').getAttribute('content'),/abcdee-600x400.png$/);
  assert.equal(await page.locator('main > p a').textContent(),'TEST article back');
  assert.equal(await page.locator('article figure img').count(),2);
  assert.deepEqual(await page.locator('article figure img').evaluateAll(imgs=>imgs.map(i=>i.alt)),['First image','Second image']);
  assert.equal(await page.locator('article script').count(),0);
  assert.equal(await page.locator('article img[onerror]').count(),0);
  assert.equal(await page.locator('article h2').textContent(),'Heading');
  assert.equal(await page.locator('article ul ul li').textContent(),'Nested');
  assert.equal(await page.locator('article blockquote').textContent(),'Quote');
  assert.equal(await page.locator('article pre code').textContent(),'<img onerror=alert(1)>');
  assert.equal(await page.locator('article a[href="https://example.com"]').count(),1);
  const text=await page.locator('article').textContent();
  assert.ok(text.indexOf('Before')<text.indexOf('First image caption') && text.indexOf('First image caption')<text.indexOf('Between') && text.indexOf('Between')<text.indexOf('Second image caption') && text.indexOf('Second image caption')<text.indexOf('After'));
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth));
  await page.screenshot({path:process.env.HOME+'/.hermes/profiles/coder/cache/scratch/cms-writing-fixture.png',fullPage:true});
  await page.goto('http://127.0.0.1:18766/writing/');
  assert.equal(await page.locator('meta[name="description"]').getAttribute('content'),'TEST description');
  assert.match(await page.locator('meta[property="og:image"]').getAttribute('content'),/abcdef-400x300.png$/);
  assert.equal(await page.locator('h1').textContent(),'TEST Archive');
  assert.equal(await page.locator('a[href="/writing/test-only-article/"]').count(),1);
  assert.equal(await page.locator('a[href="/writing/secret/"]').count(),0);
  await page.goto('http://127.0.0.1:18766/');
  assert.equal(await page.title(),'TEST SEO');
  assert.match(await page.locator('meta[property="og:image"]').getAttribute('content'),/abcdef-400x300.png$/);
  assert.equal(await page.locator('.wordmark').textContent(),'TEST WORDMARK');
  assert.equal(await page.locator('.role').textContent(),'TEST expertise');
  assert.equal(await page.locator('.intro').textContent(),'TEST bio');
  assert.equal(await page.locator('.site-header nav a').first().textContent(),'TEST Writing');
  assert.equal(await page.locator('footer nav a').first().textContent(),'TEST Footer');
  assert.equal(await page.locator('#contact-title').textContent(),'TEST question');
  assert.deepEqual(await page.locator('main > section').evaluateAll(els=>els.map(e=>e.id)),['top','experience','writing','tools','achievements','certificates','contact']);
  assert.equal((await page.locator('#experience-title').textContent()).trim(),'TEST Career');
  assert.equal(await page.locator('a[href="#projects"]').count(),0);
  assert.equal(await page.getByText('TEST Hidden').count(),0);
  await page.locator('#command').fill('ls');
  await page.locator('#command-form').evaluate(form=>form.requestSubmit());
  assert.equal(await page.locator('#terminal-output a[href="#projects"]').count(),0);
  await page.locator('#command').fill('projects');
  await page.locator('#command-form').evaluate(form=>form.requestSubmit());
  assert.notEqual(await page.evaluate(()=>location.hash),'#projects');
  assert.equal(await page.locator('a[href="mailto:test@example.com"]').textContent(),'TEST contact');
  await page.locator('#command').fill('cat README.md');
  await page.locator('#command-form').evaluate(form=>form.requestSubmit());
  await page.locator('#terminal-output').getByText('TEST README').waitFor();
  assert.equal(await page.locator('a[href="/writing/test-only-article/"]').count(),1);
  console.log('Synthetic actual generated DOM, mobile overflow, archive/home links and draft exclusion: PASS');
} finally { if(browser) await browser.close(); server.kill(); }
